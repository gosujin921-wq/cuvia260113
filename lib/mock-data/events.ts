// 타입 정의
// ============================================================================

/**
 * 이벤트 기본 구조 인터페이스
 * events-data.ts의 BaseEvent와 동일한 구조
 */
interface BaseEvent {
  /** 
   * 이벤트 ID (규칙에 따른 고유 식별자)
   * 형식: [도메인코드]-[연도월일]-[시퀀스]
   * 예시: A-20241124-001, A-20260107-004
   */
  eventId: string;
  
  /** 
   * 내부 사용 ID (시스템 내부에서 사용하는 식별자)
   * eventId와 동일한 값을 사용 (통일)
   * 형식: [도메인코드]-[연도월일]-[시퀀스]
   * 예시: A-20241124-001, A-20260107-004
   */
  id: string;
  
  /**
   * 이벤트 유형 (사건 종류)
   * 예시: '폭행 · 상해', '절도 · 강도', '실종 · 미아', '유괴 의심 · 아동 실종'
   */
  type: string;
  
  /**
   * 이벤트 제목 (사건 간단 요약)
   * 예시: '흉기 소지 남성 위협 행동', '김도연(남, 22세, 장애) 실종 신고'
   */
  title: string;
  
  /**
   * 발생 시간 (HH:MM 형식)
   * 예시: '18:42', '09:30'
   */
  time: string;
  
  /**
   * 발생 위치 (주소 또는 장소 설명)
   * 예시: '별빛구 은하로363번길 48', '별빛구 은하로363번길 48 일원'
   */
  location: string;
  
  /**
   * 이벤트 상세 설명 (신고 내용, 감지 내용 등)
   * 예시: '112 신고자 "흉기 든 남성이 위협 중"'
   */
  description?: string;
  
  /**
   * 신고/감지 출처 (신고 기관 또는 시스템)
   * 예시: '안양112센터', '경찰청', 'AI'
   */
  source?: string;
  
  /**
   * 위험도
   * - 긴급: 긴급 대응이 필요한 심각한 사건
   * - 경계: 주의를 기울여야 하는 사건
   * - 주의: 일반적인 모니터링이 필요한 사건
   * - 일반: 평상시 모니터링 수준의 사건
   */
  risk: '긴급' | '경계' | '주의' | '일반';
  
  /**
   * 이벤트 상태
   * - 진행중: 현재 진행 중인 이벤트
   * - 종결: 처리 완료된 이벤트
   * - 오탐: 오탐으로 판단된 이벤트
   */
  status: '진행중' | '종결' | '오탐';
  
  /**
   * 전파 이력
   * 전파를 보낸 횟수와 마지막 전파 시간
   */
  broadcastHistory?: {
    count: number;
    lastBroadcastTime?: string; // ISO 8601 형식 또는 'YYYY-MM-DD HH:mm:ss'
  };
  
  /**
   * 도메인 코드 (이벤트 카테고리)
   * - A: 112 치안 · 방범 (경찰 사건)
   * - B: 119 재난 · 구조 (소방 사건)
   * - C: 사회적 약자 보호 (취약 계층 보호)
   * - D: AI 이상행동 (AI 감지 이상 행동)
   * - E: 재난 (NDMS 등 재난 관련)
   * - F: 도시 운영 · 환경 (시설 관리, 환경 등)
   */
  domain: 'A' | 'B' | 'C' | 'D' | 'E' | 'F';
}

