// 이벤트 ID 생성용 기준 날짜 (YYYYMMDD 형식)
// 현재는 사용하지 않음 (모든 이벤트 ID를 명시적으로 지정)
const today = '20241124'; // 2024년 11월 24일
let sequence = 1; // 시퀀스 카운터 (현재 미사용)

/**
 * 이벤트 ID 생성 함수
 * 형식: [도메인코드]-[연도월일]-[시퀀스(3자리)]
 * 예시: A-20241124-001, B-20241124-002
 * 
 * @param domain - 도메인 코드 ('A' | 'B' | 'C' | 'D' | 'E' | 'F')
 * @returns 생성된 이벤트 ID
 * 
 * @deprecated 현재는 모든 이벤트 ID를 명시적으로 지정하여 사용
 */
const generateEventId = (domain: 'A' | 'B' | 'C' | 'D' | 'E' | 'F'): string => {
  return `${domain}-${today}-${String(sequence++).padStart(3, '0')}`;
};

